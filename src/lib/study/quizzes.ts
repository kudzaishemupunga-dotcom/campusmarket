export const QUESTION_BY_ID: ReadonlyMap<string, QuizQuestion> = new Map(
  QUIZ_QUESTIONS.map((q) => [q.id, q])
);

export function getQuizQuestions(options: {
  subjectId: StudySubjectId | 'mixed';
  tier?: QuizTierFilter;
  limit?: number;
}): QuizQuestion[] {
  const { subjectId, tier = 'all', limit } = options;
  let pool =
    subjectId === 'mixed'
      ? [...QUIZ_QUESTIONS]
      : QUIZ_QUESTIONS.filter((q) => q.subjectId === subjectId);

  if (tier !== 'all') {
    pool = pool.filter((q) => q.difficulty === tier);
  }

  if (subjectId === 'mixed') {
    // Interleave subjects so mixed challenges cover broad IGCSE domains evenly
    const bySubject = new Map<StudySubjectId, QuizQuestion[]>();
    for (const q of pool) {
      const list = bySubject.get(q.subjectId) ?? [];
      list.push(q);
      bySubject.set(q.subjectId, list);
    }
    const interleaved: QuizQuestion[] = [];
    let added = true;
    let index = 0;
    while (added) {
      added = false;
      for (const list of bySubject.values()) {
        if (index < list.length) {
          interleaved.push(list[index]);
          added = true;
        }
      }
      index += 1;
    }
    pool = interleaved;
  }

  if (typeof limit === 'number' && limit > 0) {
    return pool.slice(0, limit);
  }
  return pool;
}
